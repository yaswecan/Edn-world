import {enterAssignedTerminal} from '../tests/fixtures/exploration.mjs';
import assert from 'node:assert/strict';
import {parseArgs} from 'node:util';
import {existsSync} from 'node:fs';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium,expect} from '@playwright/test';
import {studentPreview} from './lib/student-preview.mjs';
import {createApp} from '../server/app.mjs';
import {lanAddress} from '../server/local-network.mjs';

const {values}=parseArgs({options:{source:{type:'string'},date:{type:'string'},lan:{type:'boolean'}}});
const fixture=await studentPreview({source:values.source,date:values.date});
const {store,lesson}=fixture,directory=values.lan?'test-results/student-access-lan':'test-results/student-access';
let base=fixture.base,lanServer;
if(values.lan){
 const host=lanAddress();lanServer=createApp(store).listen(0,host);
 await new Promise((resolve,reject)=>{lanServer.once('listening',resolve);lanServer.once('error',reject);});
 base=`http://${host}:${lanServer.address().port}`;
}
await mkdir(directory,{recursive:true});
const chrome=process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const errors=[],report={scope:'Local student login, daily lesson and arcade round trip; disposable in-memory database',checks:[]};
let browser,page;
try {
 browser=await chromium.launch({headless:true,...existsSync(chrome)?{executablePath:chrome}:{}});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 await context.route('**/*',route=>new URL(route.request().url()).origin===base?route.continue():route.abort());
 page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
 await page.goto(base+'/today');
 if(values.lan)assert.equal(await page.evaluate(()=>isSecureContext),false);
 await expect(page.getByRole('button',{name:'Élève',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByLabel('Identifiant',{exact:true}).fill('student-a');
 await page.getByLabel('Mot de passe',{exact:true}).fill(fixture.password);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 await expect(page.locator('[data-component=LessonHero] h1')).toHaveText(lesson.title);
 await expect(page.getByRole('link',{name:'Mode arcade',exact:true})).toBeVisible();
 await expect(page.locator('.shell .sidebar')).toHaveCount(0);
 await page.screenshot({path:directory+'/lesson-desktop.png',fullPage:true});
 report.checks.push('student-login-opens-daily-lesson','arcade-button-visible','no-teacher-dashboard');
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByRole('link',{name:'Mode arcade',exact:true})).toBeInViewport();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
 await page.screenshot({path:directory+'/lesson-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Continuer',exact:true}).click();
 await expect(page.locator('[data-component=DiagnosticIntro]')).toBeVisible();
 const answer=page.locator('textarea[data-answer]').first();
 const answerId=await answer.getAttribute('data-answer'),text='Réponse de test conservée après le retour de l’arcade.';
 await answer.fill(text);
 await page.getByRole('link',{name:'Mode arcade',exact:true}).click();
 await expect(page.locator('.cabinets')).toBeVisible();
 await expect(page.locator('#account-slot .account-name')).toHaveText('Élève test');
 const play=page.locator('[data-game="code-station"]');
 await expect(play).toBeEnabled();
 await play.click();
 const assigned=(await store.get('lesson_versions',lesson.versionId)).spec.codeStation.missionId;
 await enterAssignedTerminal(page,await store.get('game_missions',assigned));
 const game=page.frameLocator('.game-frame');
 await expect(game.locator('#missionCode')).toBeVisible();
 const draft=await game.locator('#missionCode').inputValue();
 await game.locator('#missionCode').fill(draft+'\n// Essai local Code Station');
 await game.locator('#saveDraft').click();
 await expect(page.locator('#game-save')).toHaveText('Partie enregistrée.');
 await page.getByRole('button',{name:'Quitter le jeu',exact:true}).click();
 await expect(play).toBeEnabled();
 report.checks.push('code-station-launches-before-diagnostic-completion','real-game-editor-and-save-available');
 const back=page.locator('.topbar .host-return');
 await expect(back).toBeVisible();
 await expect(back).toHaveAttribute('href','/today?lesson='+encodeURIComponent(lesson.id));
 await expect(page.locator('.arcade-bottomline .host-return')).toHaveAttribute('href','/today?lesson='+encodeURIComponent(lesson.id));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
 await page.screenshot({path:directory+'/arcade-mobile.png',fullPage:true});
 await back.click();
 await expect(page.locator('[data-component=DiagnosticIntro]')).toBeVisible();
 await expect(page.locator(`[data-answer="${answerId}"]`)).toHaveValue(text);
 assert.equal((await store.list('assessment_attempts')).length,1);
 report.checks.push('mobile-without-overflow','arcade-reuses-student-session','return-preserves-lesson-step-and-answer','single-diagnostic-attempt');
 // Simulate another school day without changing the real source or access rules.
 await store.put('lessons',{...await store.get('lessons',lesson.id),date:'2000-01-01'});
 await page.goto(base+'/today');
 await expect(page.getByRole('heading',{name:'Séance du jour',exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Mode arcade',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Ouvrir la séance',exact:true}).click();
 await expect(page.locator('[data-component=DiagnosticIntro]')).toBeVisible();
 await page.getByRole('link',{name:'Mode arcade',exact:true}).click();
 await expect(page.locator('.cabinets')).toBeVisible();
 await page.locator('.topbar .host-return').click();
 await expect(page.locator('[data-component=DiagnosticIntro]')).toBeVisible();
 report.checks.push('arcade-available-without-daily-lesson','direct-lesson-link-survives-arcade-on-another-date');
 process.env.EDEN_WORLD_ARCADE='0';
 await page.reload();
 await expect(page.locator('[data-component=DiagnosticIntro]')).toBeVisible();
 await expect(page.getByRole('link',{name:'Mode arcade',exact:true})).toHaveCount(0);
 assert.equal((await context.request.get(base+'/arcade')).status(),404);
 assert.deepEqual(errors,[]);
 report.checks.push('disabled-arcade-has-no-dead-link','no-browser-errors');report.status='PASS';
} catch(error) {
 report.status='FAIL';report.error=error.stack;await page?.screenshot({path:directory+'/failure.png',fullPage:true});throw error;
} finally {
 await writeFile(directory+'/report.json',JSON.stringify(report,null,2)+'\n');
 await browser?.close();
 if(lanServer){lanServer.closeAllConnections();await new Promise(resolve=>lanServer.close(resolve));}
 await fixture.close();
}
console.log(JSON.stringify(report,null,2));
